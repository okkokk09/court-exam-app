    subject = question_obj.get('subject', '')
    qid = str(question_obj.get('id', ''))
    law_ref = str(question_obj.get('law_ref', '')).strip()
    topic = str(question_obj.get('topic', '')).strip()
    explanation = str(question_obj.get('explanation', '')).strip()
    question_text = str(question_obj.get('question', '')).strip()
    category = str(question_obj.get('category', '')).strip()
    
    is_computer = (subject == 'computer' or qid.startswith('COM'))
    
    # 1. Check for specific Section Number if question relates to พ.ร.บ. บริหารราชการศาล
    sec_match = re.search(r'มาตรา\s*(?:ที่\s*)?(\d+)', f"{law_ref} {explanation} {topic}")
    if sec_match:
        sec_num = int(sec_match.group(1))
        # Find exact section in LEGAL_DB
        for key, data in LEGAL_DB.items():
            if data.get('sec_num') == sec_num and 'พ.ร.บ. ระเบียบบริหารราชการศาล' in data['title']:
                return data
            if data.get('sec_num') == sec_num and 'พระธรรมนูญ' in data['title'] and ('พระธรรมนูญ' in law_ref or 'พระธรรมนูญ' in topic):
                return data
                
    # 2. Match by high-confidence keywords
    combined_query = f"{law_ref} {topic} {question_text} {category}"
    best_match = None
    max_matches = 0
    for key, data in LEGAL_DB.items():
        matches = sum(1 for kw in data['keywords'] if kw.lower() in combined_query.lower())
        if matches > max_matches and matches >= 2:
            max_matches = matches
            best_match = data
            
    if best_match:
        return best_match
        
    # If this is a general computer question without specific IT law match, DO NOT show legal expander
    if is_computer:
        return None
        
    # 3. Dynamic automated generation (Only for Law questions)
    title = law_ref if law_ref and law_ref not in ['-', 'พ.ร.บ.'] else f'ข้อกำหนดและหลักการ: {category}'
    
    elements = []
    if any(unit in explanation for unit in ['วัน', 'ปี', 'เดือน', 'บาท', '%', 'อัตรา', 'คน']):
        nums = re.findall(r'[0-9]+(?:\.[0-9]+)?\s*(?:วัน|ปี|เดือน|ชั่วโมง|นาที|บาท|คน|อัตรา|เปอร์เซ็นต์|%|สถาน)', explanation)
        if nums:
            elements.append(f'เกณฑ์ตัวเลขสำคัญตามตัวบท: {", ".join(nums)}')
            
    elements.append(f'หลักการทางกฎหมาย/ระเบียบ: {explanation}')
    elements.append(f'หมวดหมู่วิชา: {category} ({topic})')
    
    return {
        'title': f'{title}',
        'statute_text': f'ตามหลักเกณฑ์ {title}: {explanation}',
        'elements': elements,
        'precedent': 'แนวทางปฏิบัติราชการศาลยุติธรรม: ยึดถือตามระเบียบและหนังสือเวียนของสำนักงานศาลยุติธรรม / คำพิพากษาศาลฎีกาที่วางบรรทัดฐาน',
        'pitfalls': 'ทำความเข้าใจความหมายและเงื่อนไขของตัวบทอย่างละเอียด แทนการจำเฉพาะตัวเลือก ก ข ค ง'
    }

